"""Write every file that refers to other published files by URL: the GeoServer SLDs
(Styles/GeoServer/), the index.json manifest (docs/index.json) and the paths inside the QGIS
"linked" symbol library (Styles/QGIS/bgs-symbology-linked.xml). Standard library only, so it
runs in the Docker build and in CI.

Without --base-url the paths are relative, so the files committed to the repository name no
host or owner and keep working if the repository moves:
  - index.json: relative to index.json itself (resolve them against the manifest's URL);
  - SLDs and the QGIS linked library: relative to where they are published (v3/styles/*/).
With --base-url they are absolute. Publishing does that (the Pages workflow passes the site URL
GitHub reports; the Docker build passes BASE_URL), so the published copies work from anywhere:

    python3 scripts/make_web_styles.py . --base-url https://symbology.example.org/symbology/v3

Attribute names default to the demo data (ref / ref / id); override with --symbol-field etc.
"""
import argparse, json, os, re
from xml.sax.saxutils import escape, quoteattr

ap = argparse.ArgumentParser()
ap.add_argument("root")
ap.add_argument("--base-url", default=None, help="public URL of the v3 folder; omit for relative paths")
ap.add_argument("--symbol-field", default="ref", help="point attribute holding the symbol REF, e.g. ALV")
ap.add_argument("--rotation-field", default="rotation", help="point attribute with strike/rotation in degrees clockwise (structural symbols)")
ap.add_argument("--ornament-field", default="ref", help="polygon attribute holding the ornament REF, e.g. LMST")
ap.add_argument("--line-field", default="id", help="line attribute holding the line style id, e.g. fault_thrust_observed")
a = ap.parse_args()
R, BASE = a.root, (a.base_url.rstrip("/") if a.base_url else None)

def url(path, depth):
    """URL of a published file, given as a path below v3/. Absolute with --base-url; otherwise
    relative to a file published `depth` folders below v3/ (0 = index.json, 2 = v3/styles/*/)."""
    return f"{BASE}/{path}" if BASE else "../" * depth + path
STYLE_DEPTH = 2   # SLDs and QGIS libraries are published in v3/styles/geoserver/ and v3/styles/qgis/
GRAPHICS = BASE or "paths relative to this file as published in v3/styles/geoserver/"
syms = json.load(open(f"{R}/Symbols/symbols.json"))
orns = json.load(open(f"{R}/Area-Ornaments/ornaments.json"))
lines = json.load(open(f"{R}/Line-Styles/lines.json"))
os.makedirs(f"{R}/Styles/GeoServer", exist_ok=True)

HEAD = '''<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/make_web_styles.py from BGS RR/01/01 v3. Graphics: {graphics} -->
<StyledLayerDescriptor version="1.0.0"
    xmlns="http://www.opengis.net/sld" xmlns:ogc="http://www.opengis.net/ogc"
    xmlns:xlink="http://www.w3.org/1999/xlink" xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"
    xsi:schemaLocation="http://www.opengis.net/sld http://schemas.opengis.net/sld/1.0.0/StyledLayerDescriptor.xsd">
  <NamedLayer>
    <Name>{name}</Name>
    <UserStyle>
      <Name>{name}</Name>
      <Title>{title}</Title>
      <Abstract>{abstract}</Abstract>
      <FeatureTypeStyle>
'''
TAIL = '''      </FeatureTypeStyle>
    </UserStyle>
  </NamedLayer>
</StyledLayerDescriptor>
'''
def filt(field, value):
    return (f"          <ogc:Filter><ogc:PropertyIsEqualTo><ogc:PropertyName>{field}</ogc:PropertyName>"
            f"<ogc:Literal>{escape(value)}</ogc:Literal></ogc:PropertyIsEqualTo></ogc:Filter>\n")
def graphic(href, size, rotation=None, indent=12):
    p = " " * indent
    rot = f"{p}  <Rotation><ogc:PropertyName>{rotation}</ogc:PropertyName></Rotation>\n" if rotation else ""
    return (f"{p}<Graphic>\n{p}  <ExternalGraphic>\n{p}    <OnlineResource xlink:type=\"simple\" xlink:href={quoteattr(href)}/>\n"
            f"{p}    <Format>image/svg+xml</Format>\n{p}  </ExternalGraphic>\n{p}  <Size>{size}</Size>\n{rot}{p}</Graphic>\n")

# ---- symbols: one rule per REF, size = sprite height at 1x (px) ----
out = [HEAD.format(graphics=GRAPHICS, name="bgs_symbols", title="BGS cartographic symbols (RR/01/01 v3)",
                   abstract=escape(f"Point symbols keyed on attribute '{a.symbol_field}'. Structural symbols rotate by '{a.rotation_field}' (degrees clockwise)."))]
for s in syms:
    rot = a.rotation_field if s["group"] == "Structural" else None
    out.append(f"        <Rule>\n          <Name>{escape(s['ref'])}</Name>\n          <Title>{escape(s['description'])}</Title>\n"
               + filt(a.symbol_field, s["ref"])
               + "          <PointSymbolizer>\n" + graphic(url(f"symbols/svg/{s['ref']}.svg", STYLE_DEPTH), s["sprite_px"][1], rot)
               + "          </PointSymbolizer>\n        </Rule>\n")
out.append(TAIL)
open(f"{R}/Styles/GeoServer/bgs_symbols.sld", "w").write("".join(out))

# ---- ornaments: GraphicFill with the repeat tile ----
out = [HEAD.format(graphics=GRAPHICS, name="bgs_ornaments", title="BGS area ornaments (RR/01/01 v3)",
                   abstract=escape(f"Ornament fill patterns keyed on attribute '{a.ornament_field}'. Transparent tiles: draw a colour fill in a layer underneath."))]
for o in orns:
    out.append(f"        <Rule>\n          <Name>{escape(o['ref'])}</Name>\n          <Title>{escape(o['description'])}</Title>\n"
               + filt(a.ornament_field, o["ref"])
               + "          <PolygonSymbolizer>\n            <Fill>\n              <GraphicFill>\n"
               + graphic(url(f"ornaments/tile/{o['ref']}.svg", STYLE_DEPTH), o["sprite_px"][1], indent=16)
               + "              </GraphicFill>\n            </Fill>\n          </PolygonSymbolizer>\n        </Rule>\n")
out.append(TAIL)
open(f"{R}/Styles/GeoServer/bgs_ornaments.sld", "w").write("".join(out))

# ---- lines: GraphicStroke repeats the tile along the line ----
out = [HEAD.format(graphics=GRAPHICS, name="bgs_line_styles", title="BGS line styles (RR/01/01 v3)",
                   abstract=escape(f"Line styles keyed on attribute '{a.line_field}'. Each tile is repeated along the line (GraphicStroke)."))]
for l in lines:
    out.append(f"        <Rule>\n          <Name>{escape(l['id'])}</Name>\n          <Title>{escape(l['description'])}</Title>\n"
               + filt(a.line_field, l["id"])
               + "          <LineSymbolizer>\n            <Stroke>\n              <GraphicStroke>\n"
               + graphic(url(f"lines/tile/{l['id']}.svg", STYLE_DEPTH), l["sprite_px"][1], indent=16)
               + "              </GraphicStroke>\n            </Stroke>\n          </LineSymbolizer>\n        </Rule>\n")
out.append(TAIL)
open(f"{R}/Styles/GeoServer/bgs_line_styles.sld", "w").write("".join(out))

# ---- manifest: what is published and where (relative to the v3 folder) ----
manifest = {
    "name": "BGS cartographic standard geological symbology",
    "edition": "RR/01/01 version 3 (2002)",
    "base_url": BASE,
    "paths": "absolute" if BASE else "relative to this file: resolve them against the URL index.json was fetched from",
    "counts": {"symbols": len(syms), "ornaments": len(orns), "line_styles": len(lines)},
    "maplibre": {"sprite": url("sprites/bgs-symbology", 0),
                 "image_names": {"symbol": "sym-{REF}", "ornament": "orn-{REF}", "line": "line-{id}"}},
    "templates": {
        "symbol_svg": url("symbols/svg/{REF}.svg", 0),
        "symbol_svg_24px": url("symbols/svg-24px/{REF}_24px.svg", 0),
        "symbol_svg_48px": url("symbols/svg-48px/{REF}_48px.svg", 0),
        "ornament_tile_svg": url("ornaments/tile/{REF}.svg", 0),
        "ornament_swatch_svg": url("ornaments/swatch/{REF}.svg", 0),
        "line_tile_svg": url("lines/tile/{id}.svg", 0),
        "line_tile_png_4x": url("lines/png/{id}.png", 0),
        "line_swatch_svg": url("lines/swatch/{id}.svg", 0)},
    "catalogues": {k: url(v, 0) for k, v in {
        "symbols_json": "symbols/symbols.json", "symbols_csv": "symbols/symbols.csv",
        "ornaments_json": "ornaments/ornaments.json", "ornaments_csv": "ornaments/ornaments.csv",
        "lines_json": "lines/lines.json", "lines_csv": "lines/lines.csv"}.items()},
    "styles": {k: url(v, 0) for k, v in {
        "geoserver_symbols_sld": "styles/geoserver/bgs_symbols.sld",
        "geoserver_ornaments_sld": "styles/geoserver/bgs_ornaments.sld",
        "geoserver_line_styles_sld": "styles/geoserver/bgs_line_styles.sld",
        "qgis_library_embedded": "styles/qgis/bgs-symbology-embedded.xml",
        "qgis_library_linked": "styles/qgis/bgs-symbology-linked.xml",
        "qgis_symbols_qml": "styles/qgis/bgs_symbols.qml",
        "qgis_ornaments_qml": "styles/qgis/bgs_ornaments.qml",
        "qgis_line_styles_qml": "styles/qgis/bgs_line_styles.qml"}.items()},
    "attributes": {"symbol": a.symbol_field, "rotation": a.rotation_field, "ornament": a.ornament_field, "line": a.line_field},
}
json.dump(manifest, open(f"{R}/docs/index.json", "w"), indent=1)

# ---- QGIS linked library: written by make_qgis_styles.py (needs PyQGIS); only its paths are
# rewritten here, so CI and the Docker build can point it at the published URL without QGIS.
linked = f"{R}/Styles/QGIS/bgs-symbology-linked.xml"
if os.path.exists(linked):
    xml = open(linked, encoding="utf-8").read()
    xml, n = re.subn(r'(\bvalue=")[^"]*?((?:symbols|ornaments|lines)/(?:svg|tile|png)/[^"/]+)"',
                     lambda m: m.group(1) + url(m.group(2), STYLE_DEPTH) + '"', xml)
    open(linked, "w", encoding="utf-8").write(xml)
    print(f"QGIS linked library: {n} paths")
print("SLDs + manifest written with", BASE or "relative paths")
